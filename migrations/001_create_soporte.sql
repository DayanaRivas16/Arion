CREATE TABLE IF NOT EXISTS public.soporte (
    id_soporte BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id INTEGER NOT NULL
        REFERENCES public.usuarios (id_usuario) ON DELETE CASCADE,
    asunto VARCHAR(150) NOT NULL,
    descripcion TEXT NOT NULL,
    estado VARCHAR(30) NOT NULL DEFAULT 'pendiente',
    fecha_creacion TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS ix_soporte_estado_fecha
    ON public.soporte (estado, fecha_creacion DESC);
